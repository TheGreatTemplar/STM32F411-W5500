"""Generate the flash-resident web page. Requires Python 3 (standard library only)."""
from pathlib import Path
import gzip
import io
import base64
import re

root = Path(__file__).resolve().parents[1]
# Keep the browser icon inside the page: no extra W5500 socket/request is needed.
page_path = root / "src/web/index.html"
page = page_path.read_text(encoding="utf-8")
icon = base64.b64encode((root / "src/web/favicon-32.png").read_bytes()).decode("ascii")
page, count = re.subn(
    r'(<link rel="icon" type="image/png" sizes="32x32" href=")[^"]*(">)',
    lambda match: match[1] + "data:image/png;base64," + icon + match[2], page)
if count != 1:
    raise ValueError("Expected exactly one embedded favicon link")
logo = base64.b64encode((root / "src/web/brand-logo.png").read_bytes()).decode("ascii")
page, count = re.subn(
    r'(<img id="brand-logo" class="brand-logo" src=")[^"]*(")',
    lambda match: match[1] + "data:image/png;base64," + logo + match[2], page)
if count != 1:
    raise ValueError("Expected exactly one header logo")
page_path.write_text(page, encoding="utf-8")
html = page_path.read_bytes()
lines = ["/* Generated by scripts/embed_web.py. Edit src/web/index.html. */",
         "#ifndef WEB_PAGE_H", "#define WEB_PAGE_H", "", "static const char web_page[] =", "{"]
buffer = io.BytesIO()
with gzip.GzipFile(filename="", mode="wb", fileobj=buffer, compresslevel=9, mtime=0) as archive:
    archive.write(html)
compressed = buffer.getvalue()
# The sentinel is not part of the HTTP body. The server always uses an explicit length.
data = compressed + b"\0"
for offset in range(0, len(data), 16):
    lines.append("    " + ", ".join(f"0x{byte:02X}" for byte in data[offset:offset + 16]) + ",")
lines.extend(["};", "", "#endif", ""])
(root / "src/web_page.h").write_text("\n".join(lines), encoding="utf-8")
print("Embedded gzip page:", len(compressed), "bytes; HTML:", len(html), "bytes;")
print("Internal Flash saved:", len(html) - len(compressed), "bytes")
