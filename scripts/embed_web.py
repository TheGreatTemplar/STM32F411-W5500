"""Generate the flash-resident web page. Requires Python 3 (standard library only)."""
from pathlib import Path
import gzip
import io

root = Path(__file__).resolve().parents[1]
html = (root / "src/web/index.html").read_bytes()
lines = ["/* Generated by scripts/embed_web.py. Edit src/web/index.html. */",
         "#ifndef WEB_PAGE_H", "#define WEB_PAGE_H", "", "static const char web_page[] =", "{"]
buffer = io.BytesIO()
with gzip.GzipFile(filename="", mode="wb", fileobj=buffer, compresslevel=9, mtime=0) as archive:
    archive.write(html)
compressed = buffer.getvalue()
# The sentinel is not part of the HTTP body. The server always uses an explicit length.
data = compressed + b"\0"
for offset in range(0, len(data), 16):
    lines.append("    " + ", ".join(f"0x{byte:02X}" for byte in data[offset:offset + 16]) + ",")
lines.extend(["};", "", "#endif", ""])
(root / "src/web_page.h").write_text("\n".join(lines), encoding="utf-8")
print("Embedded gzip page:", len(compressed), "bytes; HTML:", len(html), "bytes;")
print("Internal Flash saved:", len(html) - len(compressed), "bytes")
