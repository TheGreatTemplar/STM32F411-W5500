"""Build the first-install Help archive. Served bytes live in external NOR after installation."""
from pathlib import Path
import gzip
import zlib
root = Path(__file__).resolve().parents[1]
source = (root / "documentation/help.html").read_bytes()
payload = gzip.compress(source, compresslevel=9, mtime=0)
if len(payload) > 32768 - 256:
    raise ValueError("Help archive exceeds its external Flash bank")
lines = ["/* Generated by scripts/embed_help.py from documentation/help.html. */",
         "#ifndef HELP_SEED_H", "#define HELP_SEED_H", "",
         f"#define HELP_CONTENT_CRC 0x{zlib.crc32(payload):08X}UL",
         "static const uint8_t help_seed[] =", "{"]
for offset in range(0, len(payload), 16):
    lines.append("    " + ", ".join(f"0x{byte:02X}" for byte in payload[offset:offset+16]) + ",")
lines.extend(["};", "", "#endif", ""])
(root / "src/help_seed.h").write_text("\n".join(lines), encoding="utf-8")
print(f"Help: {len(source)} HTML bytes -> {len(payload)} gzip bytes; CRC32 {zlib.crc32(payload):08X}")
