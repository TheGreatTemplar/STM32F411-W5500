$ErrorActionPreference = 'Stop'
$projectRoot = Split-Path -Parent $PSScriptRoot
$version = Get-Content -LiteralPath (Join-Path $projectRoot 'firmware/version.json') -Raw | ConvertFrom-Json
$files = @()
foreach ($directory in @('src', 'third_party', 'firmware', 'scripts'))
{
    $files += Get-ChildItem -LiteralPath (Join-Path $projectRoot $directory) -File -Recurse |
        Where-Object { $_.Name -ne 'build_info.h' -and $_.Name -ne 'web_page.h' -and $_.Extension -ne '.pyc' }
}
$files += Get-Item -LiteralPath (Join-Path $projectRoot 'adc_web_f411.uvprojx')
$manifest = [Text.StringBuilder]::new()
$fileHasher = [Security.Cryptography.SHA256]::Create()
$paths = [string[]]@($files | ForEach-Object { $_.FullName })
[Array]::Sort($paths, [StringComparer]::Ordinal)
try
{
    foreach ($filePath in $paths)
    {
        $relative = $filePath.Substring($projectRoot.Length + 1).Replace('\', '/')
        $digest = ([BitConverter]::ToString($fileHasher.ComputeHash([IO.File]::ReadAllBytes($filePath)))).Replace('-', '').ToLowerInvariant()
        [void]$manifest.Append($relative + ':' + $digest + "`n")
    }
}
finally
{
    $fileHasher.Dispose()
}
$hasher = [Security.Cryptography.SHA256]::Create()
try
{
    $hash = ([BitConverter]::ToString($hasher.ComputeHash([Text.Encoding]::UTF8.GetBytes($manifest.ToString())))).Replace('-', '').ToLowerInvariant()
}
finally
{
    $hasher.Dispose()
}
$crc = [uint32]::MaxValue
foreach ($value in [IO.File]::ReadAllBytes((Join-Path $projectRoot 'src/web/index.html')))
{
    $crc = $crc -bxor $value
    for ($bit = 0; $bit -lt 8; ++$bit)
    {
        if (($crc -band 1) -ne 0)
        {
            $crc = [uint32](($crc -shr 1) -bxor [uint32]0xEDB88320L)
        }
        else
        {
            $crc = [uint32]($crc -shr 1)
        }
    }
}
$crc = $crc -bxor [uint32]::MaxValue
$utc = [DateTime]::UtcNow.ToString("yyyy-MM-ddTHH:mm:ss'Z'")
$lines = @(
    '/* Generated by scripts/build_info.ps1 before each build. */',
    '#ifndef BUILD_INFO_H', '#define BUILD_INFO_H',
    ('#define FW_VERSION "' + $version.version + '"'),
    ('#define FW_BASE_COMMIT "' + $version.base_commit + '"'),
    ('#define FW_SOURCE_SHA256 "' + $hash + '"'),
    ('#define FW_BUILD_UTC "' + $utc + '"'),
    ('#define FW_WEB_CRC32 "' + $crc.ToString('X8') + '"'),
    '#endif', ''
)
[IO.File]::WriteAllText((Join-Path $projectRoot 'src/build_info.h'), ($lines -join "`n"), [Text.UTF8Encoding]::new($false))
Write-Host ('Build identity: ' + $version.version + ' / ' + $hash.Substring(0, 12))
